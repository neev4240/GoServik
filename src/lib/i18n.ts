const LANG_KEY = 'kaamnow_lang';

export function getStoredLanguage(): Language {
  if (typeof window === 'undefined') return 'en';
  const saved = localStorage.getItem(LANG_KEY);
  if (saved === 'en' || saved === 'hi') return saved;
  return 'en';
}

export function setStoredLanguage(lang: Language) {
  if (typeof window !== 'undefined') {
    localStorage.setItem(LANG_KEY, lang);
    window.dispatchEvent(new Event('kaamnow_lang_changed'));
  }
}

export function useLanguage() {
  const [lang, setLang] = useState<Language>(getStoredLanguage());

  useEffect(() => {
    const handler = () => {
      setLang(getStoredLanguage());
    };
    window.addEventListener('kaamnow_lang_changed', handler);
    return () => window.removeEventListener('kaamnow_lang_changed', handler);
  }, []);

  const changeLanguage = (newLang: Language) => {
    setStoredLanguage(newLang);
    setLang(newLang);
  };

  const t = (key: keyof typeof translations.en | string, fallback?: string): string => {
    const currentDict = (translations as any)[lang] || translations.en;
    if (currentDict && currentDict[key]) {
      return currentDict[key];
    }
    const defaultDict = (translations.en as any);
    if (defaultDict && defaultDict[key]) {
      return defaultDict[key];
    }
    return fallback || key;
  };

  return { lang, setLanguage: changeLanguage, t };
}
